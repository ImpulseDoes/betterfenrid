export type IconName = keyof typeof PATHS

const SVG_NS = 'http://www.w3.org/2000/svg'

export function isIconName(name: string): name is IconName {

  return name in PATHS

}

export function icon(name: IconName, size = 20): SVGSVGElement {

  const svg = document.createElementNS(SVG_NS, 'svg')

  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('width', String(size))
  svg.setAttribute('height', String(size))
  svg.setAttribute('fill', 'currentColor')
  svg.setAttribute('aria-hidden', 'true')

  const path = document.createElementNS(SVG_NS, 'path')

  path.setAttribute('d', PATHS[name])
  svg.append(path)

  return svg
}

const fittedBoxes = new Map<IconName, string>()

function fittedBox(name: IconName): string {

  const known = fittedBoxes.get(name)

  if (known) return known

  const svg = icon(name)

  svg.style.cssText = 'position:absolute;visibility:hidden'
  document.body.append(svg)

  const { x, y, width, height } = svg.querySelector('path')!.getBBox()

  svg.remove()

  const size = Math.max(width, height)
  const box = `${x + width / 2 - size / 2} ${y + height / 2 - size / 2} ${size} ${size}`

  fittedBoxes.set(name, box)

  return box
}

/** For rows next to Fenrid's icons: those fill their box, ours are drawn with a margin */
export function fittedIcon(name: IconName, size = 20): SVGSVGElement {

  const svg = icon(name, size)

  svg.setAttribute('viewBox', fittedBox(name))

  return svg
}

const SPARK_COLORS = ['#ff5c8a', '#ffd166', '#7c9cff']

export function withBurst(svg: SVGSVGElement): SVGSVGElement {

  const ring = document.createElementNS(SVG_NS, 'circle')

  ring.setAttribute('data-bf-ring', '')
  ring.setAttribute('cx', '12')
  ring.setAttribute('cy', '12')
  ring.setAttribute('r', '2')
  ring.setAttribute('fill', 'none')
  ring.setAttribute('stroke', SPARK_COLORS[0])
  ring.setAttribute('opacity', '0')
  svg.prepend(ring)

  for (let i = 0; i < 7; i++) {

    const angle = (i / 7) * Math.PI * 2 - Math.PI / 2
    const spark = document.createElementNS(SVG_NS, 'circle')

    spark.setAttribute('data-bf-spark', '')
    spark.setAttribute('cx', '12')
    spark.setAttribute('cy', '12')
    spark.setAttribute('r', '1.4')
    spark.setAttribute('fill', SPARK_COLORS[i % SPARK_COLORS.length])
    spark.setAttribute('opacity', '0')
    spark.style.setProperty('--x', `${(Math.cos(angle) * 15).toFixed(1)}px`)
    spark.style.setProperty('--y', `${(Math.sin(angle) * 15).toFixed(1)}px`)
    svg.append(spark)

  }

  return svg
}
